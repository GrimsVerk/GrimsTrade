"""coin-cap-2, post-hoc readings (written after the run's numbers were seen; not in the bar, no
new series, nothing logged). Same series and coin falls as `coin_cap2.py`, split by when the
top was, how fast the fall was, and with one unit per calendar year of the top instead of the
card's episodes (the card's market and coin-own episodes overlap in time).

    uv run python -I research/lib/coin_cap2_posthoc.py

Writes `research/results/coin-cap-2-posthoc.md`.
"""

from __future__ import annotations

import sys
from datetime import date
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import breadth_books as bb  # noqa: E402
import coin_cap2 as cc2  # noqa: E402
import coin_cap2_core as k2  # noqa: E402
from harness import RESEARCH  # noqa: E402

BOOK_START = date(2019, 3, 31)  # the coin book's start: the stop was chosen on 2019-25


def main() -> None:
    bk = cc2.build(bb.cm_book())
    n_days = bk.book.px.shape[0]
    twin, stop = cc2.series(bk)
    f_star = float(stop.ret[bk.mask].mean() / twin.ret[bk.mask].mean())
    falls = cc2.coin_falls(bk, twin)
    names = bk.book.names
    edge, fast = [], []
    for f in falls:
        lo, hi = k2.window(f, n_days)
        m_t = k2.deepest_fall(twin.ret[lo + 1 : hi + 1, f.coin])
        m_s = k2.deepest_fall(stop.ret[lo + 1 : hi + 1, f.coin])
        edge.append(f_star * m_t - m_s)
        fast.append(f.low - f.top <= 60)
    e = np.array(edge)
    fa = np.array(fast)
    yr = np.array([bk.day(f.top).year for f in falls])
    early = np.array([bk.day(f.top) < BOOK_START for f in falls])
    big2 = np.array([names[f.coin] in ("btc", "eth") for f in falls])

    def line(label: str, m: np.ndarray) -> str:
        if not m.any():
            return f"| {label} | 0 | - | - |"
        return f"| {label} | {int(m.sum())} | {float(e[m].mean()):+.1%} | {int((e[m] > 0).sum())} |"

    out = [
        "# coin-cap-2, post-hoc readings",
        "",
        "Generated by `research/lib/coin_cap2_posthoc.py`, written after `results/coin-cap-2.md` "
        "had been seen. Not in the card's bar; same series and coin falls, nothing logged. Edge "
        f"M as in the run (matched cap `f*` = {f_star:.3f}; positive: the stop lost less).",
        "",
        "## By year of the top (one unit per year instead of the card's episodes)",
        "",
        "| Year | Coin falls | Mean edge M | Falls with edge > 0 |",
        "|---|---:|---:|---:|",
    ]
    years = sorted(set(yr.tolist()))
    out += [line(str(y), yr == y) for y in years]
    ym = np.array([float(e[yr == y].mean()) for y in years])
    out += [
        "",
        f"Years with a positive mean edge: {int((ym > 0).sum())} of {len(years)} (sign test p "
        f"{k2.sign_p(int((ym > 0).sum()), len(years)):.3f}).",
        "",
        "## Splits",
        "",
        "| Coin falls | Count | Mean edge M | Edge > 0 |",
        "|---|---:|---:|---:|",
        line(f"top before {BOOK_START} (out of time for the stop's choice)", early),
        line(f"top from {BOOK_START}", ~early),
        line("fast: low within 60 days of the top", fa),
        line("slow: low more than 60 days after the top", ~fa),
        line("fast, top before the book", fa & early),
        line("slow, top before the book", ~fa & early),
        line("BTC and ETH", big2),
        line("BTC", np.array([names[f.coin] == "btc" for f in falls])),
        line("ETH", np.array([names[f.coin] == "eth" for f in falls])),
        line("all", np.ones_like(fa)),
        "",
        "## BTC and ETH with their own matched cap",
        "",
        "`f*` from the coin's own coin-days instead of the pooled book.",
        "",
        "| Coin | Own `f*` | Coin falls | Edge M per fall | Edge > 0 |",
        "|---|---:|---:|---|---:|",
    ]
    for c in ("btc", "eth"):
        j = names.index(c)
        m = bk.mask[:, j]
        f_own = float(stop.ret[m, j].mean() / twin.ret[m, j].mean())
        es = []
        for f in falls:
            if f.coin != j:
                continue
            lo, hi = k2.window(f, n_days)
            m_t = k2.deepest_fall(twin.ret[lo + 1 : hi + 1, j])
            es.append(f_own * m_t - k2.deepest_fall(stop.ret[lo + 1 : hi + 1, j]))
        out.append(
            f"| {c.upper()} | {f_own:.3f} | {len(es)} | {', '.join(f'{x:+.0%}' for x in es)} | "
            f"{sum(x > 0 for x in es)} |"
        )
    text = "\n".join(out) + "\n"
    print(text)
    (RESEARCH / "results" / "coin-cap-2-posthoc.md").write_text(text)


if __name__ == "__main__":
    main()
