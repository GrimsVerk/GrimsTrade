"""coin-cap, second reading: worst loss in the coin years only and inside deep-1's coin-crash
windows (card: research/cards/coin-cap.md, "Second reading"). Same configurations as
`coin_cap.py`, rerun unlogged; one tries row for the reading.

    uv run python -I research/lib/coin_cap_years.py

Writes `research/results/coin-cap-years.md`.
"""

from __future__ import annotations

import dataclasses
import sys
from datetime import date
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import coin_cap as cc  # noqa: E402
import cointop1_carry as ct  # noqa: E402
import common as c  # noqa: E402
import harness  # noqa: E402
import stats  # noqa: E402

from grimstrade import gym  # noqa: E402

COIN_START = date(2013, 1, 1)


def inside(run: c.Run, a: date, b: date) -> float:
    """Largest peak-to-trough fall with both ends inside [a, b]."""
    r = run.rets_between(a, b)
    return stats.max_drawdown(r) if len(r) else 0.0


def main() -> None:
    six = c.ctx("six")
    tw = c.go("baselines", "tsmom12", c.weekly(cc.TSMOM), six, "baseline", log=False)
    stop = c.go("cointop-1-stop", "stop-0.25", ct.rule(ct.stop_ok), six, "variant", log=False)
    runs = {n: c.go(cc.IDEA, n, f, six, "variant", log=False) for n, f in cc.cells().items()}
    _, wf = cc.stitch(runs, "cap-wf")
    rows = [*runs.values(), wf, stop, tw]
    stat = {}
    for r in rows:
        y = r.rets_between(COIN_START, six.end)
        w = [inside(r, a, b) for a, b in ct.CRASH]
        stat[r.variant] = (stats.max_drawdown(y), stats.cagr(y), stats.sharpe(y), max(w), w)
    s_a, s_g = stat["stop-0.25"][0], stat["stop-0.25"][1]
    out = [
        "# coin-cap, second reading: the coin years only",
        "",
        "Generated by `research/lib/coin_cap_years.py`; card `research/cards/coin-cap.md` "
        f"(second reading). Train only, gym costs, {COIN_START} .. {six.end}.",
        "",
        "| Variant | A: worst loss, coin years | CAGR, coin years | Sharpe, coin years | "
        "CAGR vs stop-0.25 | B: worst fall inside a window | B: mean of the eight |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for n, (a, g, s, bw, w) in stat.items():
        out.append(
            f"| {n} | {a:.1%} | {g:+.2%} | {s:.2f} | {g - s_g:+.2%} | {bw:.1%} | "
            f"{float(np.mean(w)):.1%} |"
        )
    out += [
        "",
        "Largest fall inside each coin-crash window (deep-1's atlas, table 4a):",
        "",
        "| Variant |" + "".join(f" {a} .. {b} |" for a, b in ct.CRASH),
        "|---|" + "---:|" * len(ct.CRASH),
    ]
    out += [f"| {n} |" + "".join(f" {x:.1%} |" for x in v[4]) for n, v in stat.items()]
    a_wf, g_wf = stat["cap-wf"][0], stat["cap-wf"][1]
    as_small = [n for n, v in stat.items() if n != "stop-0.25" and v[1] >= s_g and v[0] <= s_a]
    out += [
        "",
        "## Bar",
        "",
        f"- `cap-wf`: A {a_wf:.1%} against the stop's {s_a:.1%}; coin-years CAGR {g_wf:+.2%} "
        f"against {s_g:+.2%}: {'HOLDS' if a_wf <= s_a and g_wf > s_g else 'does not hold'}.",
        "- Series with at least the stop's CAGR and an A as small as the stop's: "
        + (", ".join(f"`{n}`" for n in as_small) if as_small else "none") + ".",
    ]  # fmt: skip
    c.write_result("coin-cap-years", "\n".join(out))
    if not c.DRY:
        i = (COIN_START - wf.days[0]).days
        eq = wf.equity[i:] / wf.equity[i] * gym.START_CASH
        row = dataclasses.replace(
            wf, variant="cap-wf coin years reread", days=wf.days[i:], equity=eq
        )
        harness._log(row, "robustness", COIN_START, six.end)


if __name__ == "__main__":
    main()
