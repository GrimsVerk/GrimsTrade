"""Cross-check: Shiller monthly bond TR and datahub monthly gold against Damodaran's annual
10y T-bond TR and gold (research/data-long-2.md, section 2).

    uv run --with xlrd python -I research/lib/long_check.py

Years 1928-2024 only: 2025 reaches into the held-out year (from 2025-11-11) and is left out.
Writes research/results/data-long-2-crosscheck.md.
"""

from __future__ import annotations

import importlib
import math
import sys
from collections.abc import Sequence
from datetime import date
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))

import long_bond as lb  # noqa: E402
import long_gold as lg  # noqa: E402

FIRST, LAST = 1928, 2024
OUT = lb.RESEARCH / "results" / "data-long-2-crosscheck.md"


def damodaran(path: Path | None = None) -> dict[int, tuple[float, float]]:
    """Year -> (10y T-bond TR, gold return) from sheet "Returns by year"."""
    path = path or lg.cache_root() / "damodaran" / "2026-11-18" / "histretSP.xls"
    xlrd: Any = importlib.import_module("xlrd")
    sh = xlrd.open_workbook(str(path)).sheet_by_name("Returns by year")
    rows = [sh.row_values(i) for i in range(sh.nrows)]
    head = next(i for i, r in enumerate(rows) if r and r[0] == "Year")
    labels = [str(x).strip() for x in rows[head]]
    bond = labels.index("US T. Bond (10-year)")
    gold = labels.index("Gold*")
    out: dict[int, tuple[float, float]] = {}
    for r in rows[head + 1 :]:
        if not isinstance(r[0], float):
            break
        out[int(r[0])] = (float(r[bond]), float(r[gold]))
    return out


def by_year(rets: Sequence[tuple[date, float]], shift: int = 0) -> dict[int, float]:
    """Compound gross monthly returns into calendar years; `shift` months moves the window
    later (shift=1: February to January)."""
    acc: dict[int, list[float]] = {}
    for d, g in rets:
        m = d.year * 12 + d.month - 1 - shift
        acc.setdefault(m // 12, []).append(g)
    return {y: math.prod(v) - 1 for y, v in acc.items() if len(v) == 12}


def stats(gaps: list[float]) -> str:
    n = len(gaps)
    mean = sum(gaps) / n
    mad = sum(abs(x) for x in gaps) / n
    big = sum(abs(x) > 0.02 for x in gaps)
    return f"{n} | {mean:+.2%} | {mad:.2%} | {max(gaps, key=abs):+.1%} | {big}"


def corr(a: list[float], b: list[float]) -> float:
    ma, mb = sum(a) / len(a), sum(b) / len(b)
    num = sum((x - ma) * (y - mb) for x, y in zip(a, b, strict=True))
    den = math.sqrt(sum((x - ma) ** 2 for x in a) * sum((y - mb) ** 2 for y in b))
    return num / den


def main() -> None:
    dam = damodaran()
    bond = lb.load()
    gold_px = lg.load()
    gold = lg.returns(gold_px)
    years = [y for y in range(FIRST, LAST + 1) if y in dam]
    out = [
        "# Cross-check against Damodaran annual (data-long-2, section 2)",
        "",
        f"Years {FIRST}-{LAST}. Gap = monthly source compounded to the year minus Damodaran. "
        "Generated by `research/lib/long_check.py`.",
        "",
        "## Summary",
        "",
        "| Series | Window | Years | Mean gap | Mean abs gap | Largest gap | Years off > 2 pts "
        "| Corr |",
        "|---|---|---:|---:|---:|---:|---:|---:|",
    ]
    bond_alt = {s: by_year(bond, s) for s in (0, 1, -1)}
    gold_dec = by_year(gold)
    avg = {}
    for y in range(FIRST - 1, LAST + 1):
        v = [p for d, p in gold_px if d.year == y]
        avg[y] = sum(v) / len(v)
    gold_avg = {y: avg[y] / avg[y - 1] - 1 for y in range(FIRST, LAST + 1)}

    def row(name: str, src: dict[int, float], col: int, lo: int, hi: int) -> None:
        ys = [y for y in years if lo <= y <= hi and y in src]
        a = [src[y] for y in ys]
        b = [dam[y][col] for y in ys]
        gaps = [x - z for x, z in zip(a, b, strict=True)]
        out.append(f"| {name} | {lo}-{hi} | {stats(gaps)} | {corr(a, b):.3f} |")

    for s, lab in ((0, "Jan-Dec"), (1, "Feb-Jan"), (-1, "Dec-Nov")):
        for lo, hi in ((1928, 1952), (1953, 1999), (2000, 2024)):
            row(f"Shiller bond, months {lab}", bond_alt[s], 0, lo, hi)
    for lo, hi in ((1928, 1970), (1971, 2024)):
        row("datahub gold, Dec/Dec", gold_dec, 1, lo, hi)
        row("datahub gold, year avg/avg", gold_avg, 1, lo, hi)

    out += [
        "",
        "## Year by year",
        "",
        "| Year | Damodaran bond | Shiller bond (Jan-Dec) | Gap | Damodaran gold "
        "| datahub Dec/Dec | Gap | datahub avg/avg | Gap |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for y in years:
        db, dg = dam[y]
        sb, gd, ga = bond_alt[0][y], gold_dec[y], gold_avg[y]
        out.append(
            f"| {y} | {db:+.1%} | {sb:+.1%} | {sb - db:+.1%} | {dg:+.1%} | {gd:+.1%} | "
            f"{gd - dg:+.1%} | {ga:+.1%} | {ga - dg:+.1%} |"
        )
    OUT.write_text("\n".join(out) + "\n")
    print("\n".join(out[:24]))


if __name__ == "__main__":
    main()
