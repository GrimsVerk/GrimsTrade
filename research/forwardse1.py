"""forward-se-1: the forward verdict's null rejection rate before and after the one-year HAC
standard error (card: research/cards/forward-se-1.md).

    uv run --with numpy python research/forwardse1.py > research/results/forward-se-1.md

Uses evalue-forward-1's null paths (`research/evalue1.py`: 52-week circular blocks of the
committed weekly returns store, train only, cut at 2025-11-09; Gaussian iid controls), the same
seed, and reads each path once at 10 and 100 years. Before: the registry's old statistics (iid
t-test with a normal p for `mean`, PSR against 0 for `sharpe`). After: `grimstrade.forward`'s
Bartlett one-year HAC test, vectorised here and checked against `forward.hac_t` path by path.
Deterministic; prints markdown.
"""

from __future__ import annotations

import math
import sys
from pathlib import Path
from statistics import NormalDist

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "research"))

from evalue1 import SEED, WEEKS, diff_paths, donors, own_paths, upper95  # noqa: E402

from grimstrade import forward  # noqa: E402

Z = NormalDist()
ALPHA = 0.025
READS = (520, 5200)  # 10 and 100 years of weekly observations
N_NULL = 10_000
N_POWER = 4_000
BATCH = 1_000


def hac_t(x: np.ndarray, per_year: float = 52) -> np.ndarray:
    """`forward.hac_t`'s statistic T for each row of x (paths x n)."""
    n = x.shape[1]
    lags = forward.lag(n, per_year)
    d = x - x.mean(axis=1, keepdims=True)
    w = (d * d).sum(axis=1) / n
    for j in range(1, lags + 1):
        w += 2 * (1 - j / (lags + 1)) * (d[:, j:] * d[:, :-j]).sum(axis=1) / n
    w *= n / (n - 1)
    return np.asarray(x.mean(axis=1) / np.sqrt(w / n))


def iid_t(x: np.ndarray) -> np.ndarray:
    n = x.shape[1]
    return np.asarray(x.mean(axis=1) / (x.std(axis=1, ddof=1) / math.sqrt(n)))


def psr_z(x: np.ndarray) -> np.ndarray:
    """The old `sharpe` path: z of PSR(0) (`stats.probabilistic_sharpe`), population moments."""
    n = x.shape[1]
    d = x - x.mean(axis=1, keepdims=True)
    sd = np.sqrt((d * d).mean(axis=1))
    sr = x.mean(axis=1) / sd
    skew = (d**3).mean(axis=1) / sd**3
    kurt = (d**4).mean(axis=1) / sd**4
    denom = 1 - skew * sr + (kurt - 1) / 4 * sr**2
    return np.asarray(np.where(denom > 0, sr * math.sqrt(n - 1) / np.sqrt(denom), 0.0))


def check_against_forward(x: np.ndarray) -> None:
    """The vectorised statistic equals the registry's own, and so does the decision."""
    for n in READS:
        t = hac_t(x[:3, :n])
        for k in range(3):
            got = forward.hac_t([float(v) for v in x[k, :n]], 52)
            assert got is not None and abs(got[0] - t[k]) < 1e-9 * max(1, abs(t[k]))
            assert (got[1] < ALPHA) == (t[k] > forward.critical(n, 52, ALPHA))


def null_cell(make: object, seed: tuple[int, ...], own: bool) -> dict[str, list[int]]:
    """Rejection counts at each read: old statistic and new."""
    rng = np.random.default_rng(list(seed))
    z = Z.inv_cdf(1 - ALPHA)
    cv = {n: forward.critical(n, 52, ALPHA) for n in READS}
    out = {"old": [0, 0], "new": [0, 0]}
    for start in range(0, N_NULL, BATCH):
        x = make(rng, min(BATCH, N_NULL - start))  # type: ignore[operator]
        if start == 0:
            check_against_forward(x)
        for i, n in enumerate(READS):
            xn = x[:, :n]
            old = psr_z(xn) if own else iid_t(xn)
            out["old"][i] += int((old > z).sum())
            out["new"][i] += int((hac_t(xn) > cv[n]).sum())
    return out


def fmt(k: int) -> str:
    return f"{k / N_NULL:.4f} (<= {upper95(k, N_NULL):.4f})"


def main() -> None:
    b, pairs, info = donors()
    rho = 0.88
    lrv_b = forward.long_run_variance([float(v) for v in b], 51) / float(b.var(ddof=1))
    lines = [
        "# forward-se-1: results",
        "",
        "Generated by `uv run --with numpy python research/forwardse1.py` (card "
        "`research/cards/forward-se-1.md`). Null paths of `research/evalue1.py` (seed "
        f"{SEED}; {len(pairs)} donors, {len(b)} weeks of `tsmom12`), {N_NULL:,} per cell, "
        f"each read once at 10 years (n {READS[0]}) and 100 years (n {READS[1]}), one-sided "
        f"alpha {ALPHA}. Old: iid t-test with a normal p (`mean`), PSR against 0 (`sharpe`). "
        "New: one-year Bartlett HAC with the fixed-b Student-t p (`forward.hac_t`; critical "
        f"value {forward.critical(READS[0], 52, ALPHA):.3f} at n {READS[0]}, "
        f"{forward.critical(READS[1], 52, ALPHA):.3f} at n {READS[1]}). The vectorised "
        "statistic was checked against `forward.hac_t` on the first paths of every cell.",
        "",
        "## 1. Null rejection rate (the card's bar)",
        "",
        "Share of null paths rejected (Clopper-Pearson 97.5% upper bound).",
        "",
        "| Null | Path | Blocks (weeks) | Old, 10 y | New, 10 y | Old, 100 y | New, 100 y |",
        "|---|---|---:|---:|---:|---:|---:|",
    ]
    cells: list[tuple[str, str, int, object, bool]] = []
    for r in (0.77, 0.88, 0.95):
        cells.append(
            (
                f"resampled, vs tsmom12, rho {r}",
                "mean",
                52,
                lambda g, m, r=r: diff_paths(g, pairs, r, 0.0, m, 52),
                False,
            )
        )
    cells.append(
        ("resampled, tsmom12 vs 0", "sharpe", 52, lambda g, m: own_paths(g, b, 0.0, m, 52), True)
    )
    cells.append(
        ("gaussian, difference", "mean", 1, lambda g, m: diff_paths(g, None, rho, 0.0, m), False)
    )
    cells.append(("gaussian, vs 0", "sharpe", 1, lambda g, m: own_paths(g, None, 0.0, m), True))
    extra = [
        (
            f"resampled, vs tsmom12, rho {rho}",
            "mean",
            104,
            lambda g, m: diff_paths(g, pairs, rho, 0.0, m, 104),
            False,
        ),
        (
            "resampled, tsmom12 vs 0",
            "sharpe",
            104,
            lambda g, m: own_paths(g, b, 0.0, m, 104),
            True,
        ),
    ]
    results = []
    for k, (name, path, block, make, own) in enumerate(cells + extra):
        c = null_cell(make, (SEED, 700 + k), own)
        results.append((name, block, c))
        if k == len(cells):
            lines += [
                "",
                "Not in the bar: dependence beyond a year (104-week blocks), which the one-year "
                "lag rule does not cover by design.",
                "",
                "| Null | Path | Blocks (weeks) | Old, 10 y | New, 10 y | Old, 100 y | "
                "New, 100 y |",
                "|---|---|---:|---:|---:|---:|---:|",
            ]
        lines.append(
            f"| {name} | {path} | {block} | {fmt(c['old'][0])} | {fmt(c['new'][0])} "
            f"| {fmt(c['old'][1])} | {fmt(c['new'][1])} |"
        )
    bar = []
    for name, _block, c in results[: len(cells)]:
        for k in c["new"]:
            rate, up = k / N_NULL, upper95(k, N_NULL)
            if name.startswith("resampled"):
                bar.append(rate <= 0.035 and up < 0.040)
            else:
                bar.append(0.015 <= rate <= 0.035)
    lines += ["", f"Card bar: **{'pass' if all(bar) else 'FAIL'}**.", ""]

    lines += [
        "## 2. Power at the new min_sample (not in the bar)",
        "",
        f"Own Sharpe 1.0 against 0, alpha {ALPHA}, power 0.8 planned. `tsmom12`'s measured "
        f"one-year long-run variance ratio (Bartlett, 51 lags, whole train record): "
        f"**{lrv_b:.2f}**. Skew 0 and kurtosis 3 assumed in the plan.",
        "",
        "| Paths | lrv in the plan | min_sample (years) | Simulated power |",
        "|---|---:|---:|---:|",
    ]
    for k, (name, src, lrv) in enumerate(
        (
            ("gaussian", None, 1.0),
            ("resampled tsmom12 (52-week blocks)", b, 1.0),
            ("resampled tsmom12 (52-week blocks)", b, max(1.0, lrv_b)),
        )
    ):
        n = forward.min_periods_sharpe(1.0, 52, ALPHA, 0.8, lrv=lrv)
        assert n <= WEEKS
        rng = np.random.default_rng([SEED, 800 + k])
        x = own_paths(rng, src, 1.0, N_POWER)[:, :n]
        pw = float((hac_t(x) > forward.critical(n, 52, ALPHA)).mean())
        lines.append(f"| {name} | {lrv:.2f} | {n} ({n / 52:.1f}) | {pw:.3f} |")
    lines += diagnostic(b, pairs)
    print("\n".join(lines))


def year_skew(x: np.ndarray) -> float:
    n = len(x) // 52 * 52
    y = x[:n].reshape(-1, 52).sum(axis=1)
    y = y - y.mean()
    return float((y**3).mean() / (y**2).mean() ** 1.5)


def diagnostic(b: np.ndarray, pairs: list) -> list[str]:  # type: ignore[type-arg]
    """Added after section 1's result (not in the card): is what is left skew of yearly sums?
    Upper against lower tail of the new statistic, 4,000 null paths, 52-week blocks."""
    out = [
        "",
        "## 3. Diagnostic (added after section 1's result, not in the card)",
        "",
        "Skewness of the source series' non-overlapping yearly sums (what a 10-year read "
        "averages, about 10 of them):",
        "",
    ]
    for r in (0.77, 0.88, 0.95):
        sk = [
            year_skew(((r - 1) * p.b + math.sqrt(1 - r**2) * p.e) / math.sqrt(2 * (1 - r)))
            for p in pairs
        ]
        out.append(
            f"- difference vs `tsmom12` at rho {r}, across donors: median "
            f"{float(np.median(sk)):+.2f}, p10 {float(np.percentile(sk, 10)):+.2f}, p90 "
            f"{float(np.percentile(sk, 90)):+.2f}"
        )
    out += [
        f"- `tsmom12` itself: {year_skew(b):+.2f}",
        "",
        "New statistic under the null, share above +cv (the one-sided test) and below -cv:",
        "",
        "| Null | n | Upper tail | Lower tail | Mean of the two |",
        "|---|---:|---:|---:|---:|",
    ]
    rng = np.random.default_rng([SEED, 999])
    for name, x in (
        ("vs tsmom12, rho 0.88", diff_paths(rng, pairs, 0.88, 0.0, 4000, 52)),
        ("tsmom12 vs 0", own_paths(rng, b, 0.0, 4000, 52)),
    ):
        for n in READS:
            t = hac_t(x[:, :n])
            cv = forward.critical(n, 52, ALPHA)
            up, lo = float((t > cv).mean()), float((t < -cv).mean())
            out.append(f"| {name} | {n} | {up:.4f} | {lo:.4f} | {(up + lo) / 2:.4f} |")
    return out


if __name__ == "__main__":
    main()
