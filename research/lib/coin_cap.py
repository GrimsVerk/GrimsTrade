"""coin-cap: a plain cap on the combined coin weight inside `tsmom12`, through the gym
(card: research/cards/coin-cap.md).

    uv run python -I research/lib/coin_cap.py          # the real run (once; logs tries)
    DRY=1 uv run python -I research/lib/coin_cap.py    # plumbing: last 120 days, no log

Writes `research/results/coin-cap.md`.
"""

from __future__ import annotations

import dataclasses
import sys
from datetime import date
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import coin_cap_core as core  # noqa: E402
import cointop1_carry as ct  # noqa: E402
import common as c  # noqa: E402
import harness  # noqa: E402
import stats  # noqa: E402

from grimstrade import gym  # noqa: E402
from grimstrade.data import CRYPTO, UNIVERSE  # noqa: E402

IDEA = "coin-cap"
CAPS = (0.10, 0.15, 0.20, 0.25)
MODES = ("cash", "rest")
ORDER = [f"cap{int(x * 100)}-{m}" for x in CAPS for m in MODES]
DEFAULT = "cap15-cash"
YEARS = range(2016, 2026)
COINS = frozenset(s for s in harness.SYMS if UNIVERSE[s] == CRYPTO)
TSMOM = c.slots(c.tsmom_signal)


def capped(cap: float, mode: str) -> c.ResearchStrategy:
    return c.weekly(lambda view: core.cap_coins(TSMOM(view), COINS, cap, mode))


def cells() -> dict[str, c.ResearchStrategy]:
    return {f"cap{int(x * 100)}-{m}": capped(x, m) for x in CAPS for m in MODES}


def stitch(runs: dict[str, c.Run], name: str) -> tuple[dict[int, str], c.Run]:
    base = runs[DEFAULT]
    ords = np.array([d.toordinal() for d in base.days[1:]])
    picks, r = core.walk_forward(ords, {n: x.rets for n, x in runs.items()}, ORDER, YEARS, DEFAULT)
    eq = base.equity[0] * np.concatenate([[1.0], np.cumprod(1 + r)])
    return picks, dataclasses.replace(base, variant=name, equity=eq)


def line(run: c.Run, tw: c.Run, stop: c.Run) -> str:
    d = c.describe(run)
    crash = sum(ct.tot(run, a, b) for a, b in ct.CRASH)
    return (
        f"| {run.variant} | {d['sharpe']:.2f} | {d['cagr']:+.2%} | {c.growth(run):+.2%} | "
        f"{d['mdd']:.1%} | {d['cagr'] - c.describe(tw)['cagr']:+.2%} | "
        f"{d['cagr'] - c.describe(stop)['cagr']:+.2%} | {crash:+.1%} |"
    )


HEAD = [
    "| Variant | Sharpe | CAGR | Log growth | Worst loss | CAGR vs tsmom12 | CAGR vs stop-0.25 "
    "| Coin-crash windows summed |",
    "|---|---:|---:|---:|---:|---:|---:|---:|",
]


def main() -> None:
    six = c.ctx("six")
    twin_f = c.weekly(TSMOM)
    stop_f = ct.rule(ct.stop_ok)

    # look-ahead checks before any number
    tw = c.go("baselines", "tsmom12", twin_f, six, "baseline", log=False)
    same = c.go(IDEA, "cap100", capped(1.0, "cash"), six, "baseline", log=False)
    if [d.weights for d in same.decisions] != [d.weights for d in tw.decisions]:
        raise AssertionError("cap of 100% differs from tsmom12")
    for f in (capped(0.10, "rest"), capped(0.25, "cash")):
        harness.check_against_gym(f, six.hist, ct.CHECK_DAYS)
    print("look-ahead checks passed", flush=True)

    stop = c.go("cointop-1-stop", "stop-0.25", stop_f, six, "variant", log=False)
    ew = c.go("baselines", "equal-weight", c.weekly(c.equal_weight), six, "baseline", log=False)
    runs = {n: c.go(IDEA, n, f, six, "variant") for n, f in cells().items()}
    for n, r in runs.items():
        worst = max(sum(d.weights.get(s, 0.0) for s in COINS) for d in r.decisions)
        if worst > float(n[3:5]) / 100 + 1e-9:
            raise AssertionError(f"{n}: coin weight {worst}")
    picks, wf = stitch(runs, "cap-wf")
    if not c.DRY:
        harness._log(wf, "variant", six.start, six.end)

    out = [
        "# coin-cap: cap the combined coin weight inside tsmom12",
        "",
        "Generated by `research/lib/coin_cap.py`; card `research/cards/coin-cap.md`; reading in "
        "`research/coin-cap.md`. Six live assets, gym costs, train only "
        f"({six.start} .. {six.end}). `cap-wf` is the walk-forward stitch (its turnover and "
        "exposure columns are `cap15-cash`'s, not its own).",
        "",
        c.table([*runs.values(), wf, stop, tw, ew], versus=tw),
        "",
        "Growth and the coin-crash windows (deep-1's atlas, table 4a):",
        "",
        *HEAD,
        *[line(r, tw, stop) for r in [*runs.values(), wf, stop, tw]],
        "",
        "Walk-forward picks (growth over worst loss on all train days before the year): "
        + ", ".join(f"{y} `{n}`" for y, n in picks.items()),
        "",
        "Total return inside each of the protocol's stress windows:",
        "",
        c.stress_table([*runs.values(), wf, stop, tw]),
        "",
    ]
    a, b = c.align(wf, stop)
    diff_s, p_s, lo_s, hi_s = stats.sharpe_diff_boot(a, b)
    out += [
        f"`cap-wf` against `stop-0.25`: Sharpe difference {diff_s:+.3f} "
        f"(p = {p_s:.2f}; 90% range {lo_s:+.2f}..{hi_s:+.2f}).",
        "",
    ]

    # double costs
    costs2 = {k: gym.Costs(fee=v.fee * 2, slip=v.slip * 2) for k, v in gym.COSTS.items()}

    def at2(idea: str, name: str, f: c.ResearchStrategy, log: bool) -> c.Run:
        return harness.run(
            idea, name, f, kind="robustness", panel=six.panel, history=six.hist, start=six.start,
            end=six.end, costs=costs2, log=log and not c.DRY,
        )  # fmt: skip

    tw2 = at2("robustness", "tsmom12-2xcost", twin_f, False)
    stop2 = at2("cointop-1-stop", "stop-0.25-2xcost", stop_f, False)
    runs2 = {n: at2(IDEA, f"{n}-2xcost", f, True) for n, f in cells().items()}
    picks2, wf2 = stitch({n: runs2[n] for n in ORDER}, "cap-wf-2xcost")
    if not c.DRY:
        harness._log(wf2, "robustness", six.start, six.end)
    out += [
        "## Double costs",
        "",
        *HEAD,
        *[line(r, tw2, stop2) for r in [*runs2.values(), wf2, stop2, tw2]],
        "",
        "Picks at double costs: " + ", ".join(f"{y} `{n}`" for y, n in picks2.items()),
        "",
    ]

    # the bar
    d, ds, dt = c.describe(wf), c.describe(stop), c.describe(tw)
    d2, ds2 = c.describe(wf2), c.describe(stop2)
    bars = [
        ("1. Worst loss no larger than `stop-0.25`'s", d["mdd"] <= ds["mdd"],
         f"{d['mdd']:.1%} vs {ds['mdd']:.1%} (`tsmom12` {dt['mdd']:.1%})"),
        ("2. CAGR above `stop-0.25`'s", d["cagr"] > ds["cagr"],
         f"{d['cagr']:+.2%} vs {ds['cagr']:+.2%} (`tsmom12` {dt['cagr']:+.2%})"),
        ("3. Sharpe at least `tsmom12`'s and `stop-0.25`'s",
         d["sharpe"] >= dt["sharpe"] and d["sharpe"] >= ds["sharpe"],
         f"{d['sharpe']:.3f} vs {dt['sharpe']:.3f} and {ds['sharpe']:.3f}"),
        ("4. Bars 1 and 2 at double costs", d2["mdd"] <= ds2["mdd"] and d2["cagr"] > ds2["cagr"],
         f"worst loss {d2['mdd']:.1%} vs {ds2['mdd']:.1%}; CAGR {d2['cagr']:+.2%} vs "
         f"{ds2['cagr']:+.2%}"),
    ]  # fmt: skip
    out += ["## Bar (`cap-wf`)", ""]
    out += [f"- {'PASS' if ok else 'FAIL'}: {text} ({detail})" for text, ok, detail in bars]
    n1 = sum(c.describe(r)["mdd"] <= ds["mdd"] for r in runs.values())
    n2 = sum(
        c.describe(r)["mdd"] <= ds["mdd"] and c.describe(r)["cagr"] > ds["cagr"]
        for r in runs.values()
    )
    out += [
        "",
        f"Fixed cells: {n1} of 8 have a worst loss no larger than `stop-0.25`'s; {n2} of 8 have "
        "that and a higher CAGR.",
        "",
        "The held-out year stays unspent.",
    ]
    c.write_result(IDEA, "\n".join(out))


if __name__ == "__main__":
    _ = date  # dates come from the harness
    main()
