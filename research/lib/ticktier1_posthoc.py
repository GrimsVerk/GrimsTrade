"""tick-tier-1 post hoc reading aids (not on the card; chosen after the real run was seen).

    uv run python -I research/lib/ticktier1_posthoc.py    # writes results/tick-tier-1-posthoc.md

1. The post window cut at 2021-12 (without the 2022 rate shock), all classes, same bootstrap.
2. Era-drift-matched null for pooled-1's equity series: each series' daily log returns replaced
   by i.i.d. normal draws with its own mean and sd, computed separately before and after
   2009-01-01 (no trend by construction; seeds 5000 + rep, 50 reps). The point timing Delta
   (`tsmom12` minus holding, post minus pre) of the stock class shows how much a change of drift
   alone moves it.
"""

from __future__ import annotations

import json
import sys
from datetime import date
from pathlib import Path
from typing import Any

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pooled1_core as pc  # noqa: E402
import pooled2_core as qc  # noqa: E402
import ticktier1 as tt  # noqa: E402

CUT = date(2009, 1, 1)
NO_2022 = (date(2009, 1, 1), date(2021, 12, 31))
REPS = 50
TIMING = tuple(f"{r}-timing" for r in tt.TIMED)
OUT = tt.RESEARCH / "results" / "tick-tier-1-posthoc.md"


def era_null(bill: list[tuple[date, float]], reps: int = REPS) -> dict[str, list[float]]:
    import pooled1 as p1

    raw = p1.load_all()
    res: list[dict[str, float]] = []
    for b in range(reps):
        rng = np.random.default_rng(5000 + b)
        sim = []
        for n, g, days, px in raw:
            lr = np.diff(np.log(px))
            post = np.array([d >= CUT for d in days[1:]])
            x = np.empty(len(lr))
            for m in (post, ~post):
                if m.sum() > 1:
                    x[m] = rng.normal(lr[m].mean(), lr[m].std(), int(m.sum()))
            sim.append((n, g, days, 100 * np.exp(np.concatenate([[0.0], np.cumsum(x)]))))
        ms = []
        for m in p1.run_all(sim, quiet=True):
            bb = tt._bill_steps(m.d, bill)
            bar = np.zeros(len(m.px))
            bar[1:] = m.px[1:] / m.px[:-1] - 1
            ser = {r: m.daily[r] - m.pos[r] * bb for r in tt.TIMED}
            ser["hold"] = bar - bb
            mk = qc.Mkt(m.name, "EQ-" + m.group, "w", np.zeros(0, dtype=np.int64))
            for r, v in ser.items():
                f, w = pc.weekly(m.d, v, m.start)
                mk.periods, mk.rets[r] = f, w
            ms.append(mk)
        s = tt.analyse(ms, draws=2)["sum"]
        res.append({r: float(s[r]["EQ"]["est"]) for r in ("tsmom12", "hold", *TIMING)})
        print(f"  null {b + 1}/{reps}", file=sys.stderr)
    return {
        k: [
            float(np.mean([r[k] for r in res])),
            float(np.percentile([r[k] for r in res], 5)),
            float(np.percentile([r[k] for r in res], 95)),
        ]
        for k in res[0]
    }


def main() -> None:
    import long_x_build as lb

    bill = lb.alfred("DTB3")
    s = tt.analyse(tt.equity_markets(bill) + tt.nonequity_markets(), post=NO_2022)["sum"]
    null = era_null(bill)
    L = [
        "# tick-tier-1: post hoc reading aids",
        "",
        "Not on the card; chosen after the real run (`results/tick-tier-1.md`) was seen. "
        "Generated by `research/lib/ticktier1_posthoc.py`.",
        "",
        "## 1. Post window 2009-01..2021-12 (without 2022)",
        "",
        "| Series | EQ Delta | FX Delta | BD Delta | CM Delta | C (SE, z) |",
        "|---|---:|---:|---:|---:|---|",
    ]
    for r in (*tt.RULES, *TIMING):
        x = s[r]
        cells = " | ".join(f"{tt.f2(x[k]['est'])} ({x[k]['se']:.2f})" for k in tt.CLASSES)
        L.append(f"| `{r}` | {cells} | {tt.est_cell(x['C'])} |")
    L += [
        "",
        f"## 2. Era-drift-matched i.i.d. null, stock class (pooled-1's series), {REPS} reps",
        "",
        "Point Delta of the stock class (post minus pre) when each series keeps its own drift "
        "and volatility in each era but has no trend. Mean (5%..95% over reps).",
        "",
        "| Series | Null mean | 5% | 95% |",
        "|---|---:|---:|---:|",
    ]
    for k, v in null.items():
        L.append(f"| `{k}` | {tt.f2(v[0])} | {tt.f2(v[1])} | {tt.f2(v[2])} |")
    L.append("")
    OUT.write_text("\n".join(L))
    data: dict[str, Any] = {"no_2022": s, "era_null_eq": null}
    OUT.with_suffix(".json").write_text(json.dumps(data, indent=1, default=float) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
